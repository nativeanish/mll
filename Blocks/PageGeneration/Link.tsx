import type { BlockData } from "@/store/useBlockStore";

interface Props {
  block: BlockData;
}

// Pick an icon based on the block's alt/name; fallback to a generic link icon
function getIconFor(block: string) {
  if (block === "Twitter") return <Twitter />;
  if (block === "Telegram") return <Telegram />;
  if (block === "Discord") return <Discord />;
  if (block === "Farcaster") return <Faracaster />;
  if (block === "Medium") return <Medium />;
  if (block === "Youtube") return <Youtube />;
  if (block === "Github") return <Github />;
  if (block === "Instagram") return <Instagram />;
  if (block === "Facebook") return <Facebook />;
  if (block === "Linkedin") return <Linkedin />;
  if (block === "Twitch") return <Twitch />;
  if (block === "Reddit") return <Reddit />;
  if (block === "Snapchat") return <Snapchat />;
  if (block === "BlueSky") return <BlueSky />;
  if (block === "Url") return <Url />;
  if (block === "Email") return <Email />;
  if (block === "Odysee") return <Odysee />;
  if (block === "Mirror") return <Mirror />;
  return <UndefinedLink />;
}

function Link({ block }: Props) {
  const alt = block.alt;
  const name = block.name;
  const uuid = block.id;
  const tooltipLabel = `${name || alt || "link"}`;

  const getStringField = (obj: unknown, key: string): string | undefined => {
    if (
      obj &&
      typeof obj === "object" &&
      key in (obj as Record<string, unknown>)
    ) {
      const value = (obj as Record<string, unknown>)[key];
      return typeof value === "string" ? value : undefined;
    }
    return undefined;
  };

  const isEmail = typeof alt === "string" && alt.toLowerCase() === "email";
  const email = getStringField(block.data, "email");
  const rawUrl = isEmail
    ? email
      ? `mailto:${email}`
      : "#"
    : getStringField(block.data, "url") || "#";
  const desc = (getStringField(block.data, "description") || "").trim();

  const refDomain = "metalinks.ar.io";
  const finalUrl = (() => {
    try {
      const u = new URL(rawUrl, window.location.href);
      if (
        (u.protocol === "http:" || u.protocol === "https:") &&
        !u.searchParams.has("ref") &&
        !u.searchParams.has("referrer") &&
        !u.searchParams.has("utm_source")
      ) {
        u.searchParams.set("ref", refDomain);
      }
      return u.toString();
    } catch {
      return rawUrl;
    }
  })();

  return (
    <div
      className="relative inline-block group"
      data-uuid={uuid}
      data-description={desc || undefined}
    >
      <a href={finalUrl} target="_blank" rel="noopener" referrerPolicy="origin">
        <button
          className="w-10 h-10 flex items-center justify-center relative overflow-hidden rounded-full bg-white shadow-md shadow-gray-200 transition-all duration-300"
          aria-label={tooltipLabel}
          title={tooltipLabel}
          data-uuid={uuid}
          data-description={desc || undefined}
        >
          {getIconFor(alt)}
        </button>
      </a>
      <div className="pointer-events-none absolute -top-2 left-1/2 -translate-x-1/2 -translate-y-full rounded-md px-2 py-1 text-xs opacity-0 shadow-sm transition-opacity duration-200 group-hover:opacity-100 bg-black text-white max-w-64 whitespace-normal break-words text-center">
        <div className="font-medium">{tooltipLabel}</div>
        {desc && <div className="opacity-80 mt-0.5">{desc}</div>}
      </div>
    </div>
  );
}

